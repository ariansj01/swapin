        'id'    => $lid,
        'title' => mb_substr($ad['title'], 0, 45),
        'from'  => "#$oldCat " . getCatName($oldCat, $pdo, $catNameStmt),
        'to'    => "#$newCat " . getCatName($newCat, $pdo, $catNameStmt),
    ];
}

