    $fetchAd->execute([$lid]);
    $ad = $fetchAd->fetch(PDO::FETCH_ASSOC);
    if (!$ad) continue;
    $oldCat = (int)$ad['category_id'];
    if ($oldCat === $newCat) continue;

    $updStmt->execute([$newCat, $lid]);
    $cnt++;
