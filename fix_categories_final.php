$cnt = 0;
$report = [];
$fetchAd = $pdo->prepare("SELECT id, title, category_id FROM listings WHERE id = ?");
$updStmt = $pdo->prepare("UPDATE listings SET category_id = ? WHERE id = ?");
$catNameStmt = $pdo->prepare("SELECT name FROM categories WHERE id = ?");

function getCatName($cid, $pdo, $catNameStmt) {
    try {
        $catNameStmt->execute([$cid]);
        $r = $catNameStmt->fetchColumn();
        return $r ? $r : "CID#$cid";
    } catch (Throwable $e) { return "CID#$cid"; }
}

