        echo "  ♻️  #{$c['id']}: {$c['from_name']} → {$c['to_name']}\n";
    }
    $pdo->commit();
    echo "\n🎉 $count رکورد با موفقیت به‌روز شد.\n";
} catch (Throwable $e) {
    $pdo->rollBack();
    echo "\n❌ خطا هنگام بروزرسانی: " . $e->getMessage() . "\n";
    exit(1);
}
