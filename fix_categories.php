foreach ($ads as $a) {
    $lid = (int)$a['id'];
    $cur = (int)$a['category_id'];
    $text = $a['title'] . ' ' . $a['description'];
    $bestId = $cur;
    $bestScore = -1;

    foreach ($rules as $r) {
        [$priority, $cid, $kws] = $r;
        $score = 0;
        foreach ($kws as $kw) {
            if (mb_stripos($text, $kw) !== false) $score += $priority;
        }
        if ($score > $bestScore) {
            $bestScore = $score;
            $bestId = $cid;
        }
    }

    // اگر امتیازی پیدا نشده تغییری نده
    if ($bestScore <= 0) {
        $unchanged++;
        continue;
    }
    if ($bestId === $cur) {
        $unchanged++;
        continue;
    }

    $changes[] = [
        'id' => $lid,
        'title' => $a['title'],
        'from' => $cur,
        'to' => $bestId,
        'from_name' => $catNames[$cur] ?? "#$cur",
        'to_name' => $catNames[$bestId] ?? "#$bestId",
        'score' => $bestScore,
    ];
}

